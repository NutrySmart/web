def suma(a, b): # Define la función 'suma' (Dentro de función 'suma')
    resultado = a + b # Asigna un valor a la variable 'resultado' (Dentro de función 'suma')
    return resultado # Retorna un valor de la función (Dentro de función 'suma')

numero1 = 5 # Asigna un valor a la variable 'numero1' (Dentro de función 'suma')
numero2 = 10 # Asigna un valor a la variable 'numero2' (Dentro de función 'suma')
print(f"La suma es: {suma(numero1, numero2)}") # Muestra información en la consola (Dentro de función 'suma')